import { spawn } from 'node:child_process';
import { mkdirSync, openSync, closeSync, chmodSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const runtime = path.join(root, '.supabase-local');
const action = process.argv[2];
const commands = {
  start: ['start', '--runtime', 'native', '--eager', '--preparation', 'on-demand', '--exclude', 'realtime,storage,functions,studio,mail,analytics,pooler'],
  stop: ['stop'],
  migrate: ['migration', 'up', '--local'],
  test: ['test', 'db'],
  types: ['gen', 'types', 'typescript', '--local', '--schema', 'public'],
  advisors: ['db', 'advisors', '--local', '--type', 'all', '--level', 'warn', '--fail-on', 'error'],
};
if (!Object.hasOwn(commands, action) || process.argv.length !== 3) {
  throw new Error('Choose one local action: start, stop, migrate, test, types, or advisors. Hosted targets are not accepted.');
}
mkdirSync(runtime, { recursive: true });
const logPath = path.join(runtime, 'start.log');
const log = action === 'start' ? openSync(logPath, 'w', 0o600) : null;
if (log !== null) chmodSync(logPath, 0o600);
const child = spawn(path.join(root, 'node_modules', '.bin', 'supabase'), commands[action], {
  cwd: root,
  env: { ...process.env, SUPABASE_HOME: runtime, SUPABASE_EXPERIMENTAL_STACK: '1' },
  stdio: action === 'start' ? ['ignore', log, log] : action === 'types' ? ['ignore', 'pipe', 'inherit'] : 'inherit',
});
let generated = '';
if (action === 'types') child.stdout.setEncoding('utf8').on('data', chunk => { generated += chunk; });
child.on('error', error => { if (log !== null) closeSync(log); console.error(error.message); process.exitCode = 1; });
child.on('exit', code => {
  if (log !== null) closeSync(log);
  if (action === 'start') console.log(code === 0
    ? `Local Supabase started. Connection credentials are in the ignored ${logPath}.`
    : `Local start failed. Inspect the ignored ${logPath}; do not paste its credentials into chat.`);
  if (action === 'types' && code === 0) {
    const destination = path.join(root, 'src', 'lib', 'supabase', 'database.types.ts');
    mkdirSync(path.dirname(destination), { recursive: true });
    writeFileSync(destination, '// Generated by npm run db:types from the local database. Do not edit by hand.\n' + generated);
    console.log('Updated src/lib/supabase/database.types.ts.');
  }
  process.exitCode = code ?? 1;
});
